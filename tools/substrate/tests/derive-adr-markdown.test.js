'use strict';
// Scenarios: A new governance unit is authored as a record and its markdown is derived;
// ADR record with sub-decisions nests them; preservation: Legacy ADR files are unchanged.
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { scratchCorpus, runDerive, read, listFiles } = require('./_helpers.js');

const HEADER_PREFIX = '> **Derived from `';

test('a form: full record derives markdown at decisions/adr-NNN-<slug>.md with the canonical-record header and the ADR template section order; index records write nothing', () => {
  const c = scratchCorpus();
  const r = runDerive(c);
  assert.equal(r.status, 0, r.stderr);
  assert.deepEqual(listFiles(c.decisions), ['adr-097-empirical-grounding-filter-at-decide.md']);
  const md = read(path.join(c.decisions, 'adr-097-empirical-grounding-filter-at-decide.md'));
  const lines = md.split('\n');
  assert.ok(lines[0].startsWith(HEADER_PREFIX), lines[0]);
  assert.match(lines[0], /adr-097\.json` \(Substrate record; canonical\)\. Do not edit this file; correct the record and re-run `node tools\/substrate\/derive\.js`\.\*\*$/);
  assert.match(md, /\n# ADR-097: Empirical-Grounding Filter at DECIDE/);
  assert.match(md, /\n\*\*Status:\*\* Accepted\n/);
  const order = ['## Context', '## Decision', '### Target 2: Discriminating criterion', '### Target 3: Standalone at commitment time', '### Graduation trigger', '## Rejected alternatives', '## Consequences', '## Provenance check'];
  let last = -1;
  for (const h of order) {
    const i = md.indexOf(`\n${h}\n`);
    assert.ok(i > last, `${h} present and in order`);
    last = i;
  }
  assert.match(md, /\*\*Positive:\*\*/);
});

test('a hand edit to the derived markdown does not survive re-derivation', () => {
  const c = scratchCorpus();
  assert.equal(runDerive(c).status, 0);
  const p = path.join(c.decisions, 'adr-097-empirical-grounding-filter-at-decide.md');
  fs.appendFileSync(p, '\nHAND EDIT\n');
  assert.equal(runDerive(c).status, 0);
  assert.ok(!read(p).includes('HAND EDIT'));
});

test('derive never overwrites a file whose first line is not its header unless --replace is given, and writes nothing on refusal', () => {
  const c = scratchCorpus();
  const p = path.join(c.decisions, 'adr-097-empirical-grounding-filter-at-decide.md');
  fs.writeFileSync(p, '# ADR-097: prose canonical file\n\nOriginal prose.\n');
  const r = runDerive(c);
  assert.equal(r.status, 1);
  assert.match(r.stderr, /refus/i);
  assert.match(r.stderr, /adr-097-empirical-grounding-filter-at-decide\.md/);
  assert.equal(read(p), '# ADR-097: prose canonical file\n\nOriginal prose.\n');
  assert.deepEqual(listFiles(c.views), [], 'nothing else written on refusal');
  const r2 = runDerive(c, ['--replace']);
  assert.equal(r2.status, 0, r2.stderr);
  assert.ok(read(p).startsWith(HEADER_PREFIX));
});

test('legacy ADR files (index records) are never written: a prose file for an index record stays byte-identical', () => {
  const c = scratchCorpus();
  const legacy = path.join(c.decisions, 'adr-094-audit-round-count-convergence-saturation.md');
  const original = '# ADR-094: legacy\n\nBody.\n';
  fs.writeFileSync(legacy, original);
  assert.equal(runDerive(c).status, 0);
  assert.equal(read(legacy), original);
  assert.equal(runDerive(c, ['--replace']).status, 0);
  assert.equal(read(legacy), original);
});
